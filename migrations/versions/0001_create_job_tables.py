# Each job with its latest description version and its latest fetch outcome.
JOBS_OVERVIEW = """
CREATE VIEW jobs_overview AS
SELECT
    j.id AS job_id,
    j.job_key,
    j.source,
    j.applied,
    j.source_url,
    v.title,
    v.company,
    v.posting_url,
    v.description_text,
    v.retrieved_at,
    a.status AS last_status,
    a.detail AS last_detail,
    a.attempted_at AS last_attempted_at
FROM jobs AS j
LEFT JOIN job_versions AS v ON v.id = (
    SELECT v2.id FROM job_versions AS v2
    WHERE v2.job_id = j.id
    ORDER BY v2.retrieved_at DESC, v2.id DESC
    LIMIT 1
)
LEFT JOIN job_fetch_attempts AS a ON a.id = (
    SELECT a2.id FROM job_fetch_attempts AS a2
    WHERE a2.job_id = j.id
    ORDER BY a2.attempted_at DESC, a2.id DESC
    LIMIT 1
)
"""


